package usecase

import (
	"context"
	"fmt"
	"github.com/bookreading/backend/internal/domain"
	"github.com/bookreading/backend/internal/infrastructure/aiservice"
	"github.com/google/uuid"
)

type chapterUseCase struct {
	chapterRepo         domain.ChapterRepository
	terminologyRepo     domain.TerminologyRepository
	translationHistRepo domain.TranslationHistoryRepository
	aiClient            aiservice.AIServiceClient
}

func NewChapterUseCase(
	chapterRepo domain.ChapterRepository,
	terminologyRepo domain.TerminologyRepository,
	translationHistRepo domain.TranslationHistoryRepository,
	aiClient aiservice.AIServiceClient,
) domain.ChapterUseCase {
	return &chapterUseCase{
		chapterRepo:         chapterRepo,
		terminologyRepo:     terminologyRepo,
		translationHistRepo: translationHistRepo,
		aiClient:            aiClient,
	}
}

func (uc *chapterUseCase) GetChapter(ctx context.Context, id string) (*domain.Chapter, error) {
	return uc.chapterRepo.GetByID(ctx, id)
}

func (uc *chapterUseCase) GetChapterByNumber(ctx context.Context, novelID string, chapterNumber int) (*domain.Chapter, error) {
	return uc.chapterRepo.GetByNovelIDAndNumber(ctx, novelID, chapterNumber)
}

func (uc *chapterUseCase) ListChapters(ctx context.Context, novelID string, limit, offset int) ([]*domain.Chapter, int, error) {
	return uc.chapterRepo.ListByNovelID(ctx, novelID, limit, offset)
}

func (uc *chapterUseCase) TranslateChapter(ctx context.Context, chapterID, targetLang string, useContext bool) (*domain.Chapter, error) {
	// Get chapter
	chapter, err := uc.chapterRepo.GetByID(ctx, chapterID)
	if err != nil {
		return nil, err
	}
	if chapter == nil {
		return nil, fmt.Errorf("chapter not found")
	}

	// Get terminology for context
	terms, err := uc.terminologyRepo.GetByNovelID(ctx, chapter.NovelID)
	if err != nil {
		return nil, err
	}

	// Build terminology list for AI
	termList := make([]aiservice.Term, 0, len(terms))
	for _, term := range terms {
		termList = append(termList, aiservice.Term{
			Original:    term.OriginalTerm,
			Translation: term.Translation,
		})
	}

	// Get translation history for context if requested
	var translationContext []aiservice.TranslationContext
	if useContext {
		// Get previous chapters' translations for context
		prevChapters, _, err := uc.chapterRepo.ListByNovelID(ctx, chapter.NovelID, int(chapter.ChapterNumber)-1, 0)
		if err == nil {
			for _, prevCh := range prevChapters {
				if prevCh.IsTranslated && prevCh.OriginalContent != "" {
					translationContext = append(translationContext, aiservice.TranslationContext{
						ChapterID:      prevCh.ID,
						SourceText:     prevCh.OriginalContent[:min(len(prevCh.OriginalContent), 1000)],
						TranslatedText: prevCh.Content[:min(len(prevCh.Content), 1000)],
					})
				}
			}
		}
	}

	// Call AI translation service
	translateReq := &aiservice.TranslateRequest{
		Text:               chapter.OriginalContent,
		SourceLang:         "zh", // Assuming Chinese source
		TargetLang:         targetLang,
		Terminology:        termList,
		TranslationContext: translationContext,
	}

	translateResp, err := uc.aiClient.TranslateContent(ctx, translateReq)
	if err != nil {
		return nil, fmt.Errorf("translation failed: %w", err)
	}

	// Update chapter with translation
	chapter.Content = translateResp.TranslatedText
	chapter.IsTranslated = true
	err = uc.chapterRepo.Update(ctx, chapter)
	if err != nil {
		return nil, err
	}

	// Save translation history
	history := &domain.TranslationHistory{
		ID:             uuid.New().String(),
		ChapterID:      chapter.ID,
		SourceText:     chapter.OriginalContent,
		TranslatedText: translateResp.TranslatedText,
		SourceLang:     "zh",
		TargetLang:     targetLang,
		ModelUsed:      translateResp.ModelUsed,
		TokensUsed:     translateResp.TokensUsed,
	}
	uc.translationHistRepo.Create(ctx, history)

	// Extract new terminology from the content if needed
	if len(terms) == 0 {
		uc.extractAndSaveTerminology(ctx, chapter)
	}

	return chapter, nil
}

func (uc *chapterUseCase) extractAndSaveTerminology(ctx context.Context, chapter *domain.Chapter) {
	extractReq := &aiservice.ExtractTerminologyRequest{
		Text:       chapter.OriginalContent,
		SourceLang: "zh",
		TargetLang: chapter.NovelID, // Will be used to fetch target lang
	}

	extractResp, err := uc.aiClient.ExtractTerminology(ctx, extractReq)
	if err != nil {
		return // Don't fail the translation if terminology extraction fails
	}

	for _, term := range extractResp.Terms {
		terminology := &domain.Terminology{
			ID:              uuid.New().String(),
			NovelID:         chapter.NovelID,
			Term:            term.Term,
			OriginalTerm:    term.Original,
			Translation:     term.Translation,
			TermType:        term.Type,
			Description:     term.Description,
			IsAutoGenerated: true,
			ConfidenceScore: term.Confidence,
		}
		uc.terminologyRepo.Create(ctx, terminology)
	}
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
