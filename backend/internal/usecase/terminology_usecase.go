package usecase

import (
	"context"
	"github.com/bookreading/backend/internal/domain"
	"github.com/google/uuid"
)

type terminologyUseCase struct {
	terminologyRepo domain.TerminologyRepository
	novelRepo       domain.NovelRepository
}

func NewTerminologyUseCase(
	terminologyRepo domain.TerminologyRepository,
	novelRepo domain.NovelRepository,
) domain.TerminologyUseCase {
	return &terminologyUseCase{
		terminologyRepo: terminologyRepo,
		novelRepo:       novelRepo,
	}
}

func (uc *terminologyUseCase) GetTerminology(ctx context.Context, novelID string) ([]*domain.Terminology, error) {
	return uc.terminologyRepo.GetByNovelID(ctx, novelID)
}

func (uc *terminologyUseCase) AddTerminology(ctx context.Context, term *domain.Terminology) error {
	term.ID = uuid.New().String()
	term.IsAutoGenerated = false
	return uc.terminologyRepo.Create(ctx, term)
}

func (uc *terminologyUseCase) UpdateTerminology(ctx context.Context, term *domain.Terminology) error {
	return uc.terminologyRepo.Update(ctx, term)
}
