package postgres

import (
	"context"
	"database/sql"
	"github.com/bookreading/backend/internal/domain"
	"github.com/jmoiron/sqlx"
)

type terminologyRepository struct {
	db *sqlx.DB
}

func NewTerminologyRepository(db *sqlx.DB) domain.TerminologyRepository {
	return &terminologyRepository{db: db}
}

func (r *terminologyRepository) Create(ctx context.Context, term *domain.Terminology) error {
	query := `
		INSERT INTO terminology (id, novel_id, term, original_term, translation, term_type, description, is_auto_generated, confidence_score)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
		ON CONFLICT (novel_id, original_term) 
		DO UPDATE SET translation = EXCLUDED.translation, term_type = EXCLUDED.term_type, description = EXCLUDED.description
	`
	_, err := r.db.ExecContext(ctx, query,
		term.ID, term.NovelID, term.Term, term.OriginalTerm,
		term.Translation, term.TermType, term.Description,
		term.IsAutoGenerated, term.ConfidenceScore,
	)
	return err
}

func (r *terminologyRepository) GetByNovelID(ctx context.Context, novelID string) ([]*domain.Terminology, error) {
	query := `SELECT * FROM terminology WHERE novel_id = $1 ORDER BY original_term ASC`
	terms := make([]*domain.Terminology, 0)
	err := r.db.SelectContext(ctx, &terms, query, novelID)
	return terms, err
}

func (r *terminologyRepository) Update(ctx context.Context, term *domain.Terminology) error {
	query := `
		UPDATE terminology 
		SET term = $2, translation = $3, description = $4
		WHERE id = $1
	`
	_, err := r.db.ExecContext(ctx, query, term.ID, term.Term, term.Translation, term.Description)
	return err
}

func (r *terminologyRepository) GetByID(ctx context.Context, id string) (*domain.Terminology, error) {
	query := `SELECT * FROM terminology WHERE id = $1`
	term := &domain.Terminology{}
	err := r.db.GetContext(ctx, term, query, id)
	if err == sql.ErrNoRows {
		return nil, nil
	}
	return term, err
}
